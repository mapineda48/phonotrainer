"""Export every brand resource (launcher icon, splash, notification icon, window colours).

Reads the masters in svg/brand/ and writes the staging tree export/res/ (design.md 7.1,
12.3 and 12.4):

  drawable/ic_launcher_background.xml, ic_launcher_foreground.xml, ic_launcher_monochrome.xml
  drawable/ic_notification.xml
  drawable/splash_mark.xml, drawable-night/splash_mark.xml          (static splash icon)
  drawable/splash_mark_animated.xml, drawable-night/...             (AVD, one shot, 700 ms)
  mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml          (adaptive icon)
  values/colors.xml, values-night/colors.xml                        (window and splash colours)

The vectors come from svg2vd.py; the animated splash wraps the generated splash vector
inline (aapt:attr) and animates its named paths: `stylus_stroke` trimPathEnd 0 -> 1 over
600 ms (pathInterpolator 0.2, 0, 0, 1), then `stylus_blot` fillAlpha 0 -> 1 from 600 to
700 ms. Nothing repeats.

Usage (from android/design-src/)
  python3 tools/brand_export.py [--out export/res]
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
BRAND = ROOT / "svg" / "brand"
PALETTE = ROOT / "palette.json"

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
NOTE = "<!-- Generated by design-src/tools/brand_export.py. {what} Edit the SVG masters, not this file. -->\n"

STROKE_MS = 600
BLOT_MS = 100


def svg2vd(src: str, out: Path, *extra: str) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, str(HERE / "svg2vd.py"), str(BRAND / src), "-o", str(out), *extra], check=True)


def animated(vector_xml: str) -> str:
    """Wrap a generated splash vector in a one-shot AnimatedVectorDrawable."""
    body = re.sub(r"<\?xml[^>]*\?>\s*", "", vector_xml)
    body = re.sub(r"<!--.*?-->\s*", "", body, flags=re.S).strip()
    # The inline vector inherits the namespaces from <animated-vector>.
    body = body.replace('\n    xmlns:android="http://schemas.android.com/apk/res/android"', "")
    body = body.replace('\n    xmlns:aapt="http://schemas.android.com/aapt"', "")
    # Start state: nothing drawn yet.
    body, n1 = re.subn(r'(android:name="stylus_stroke")', r'\1\n            android:trimPathEnd="0"', body)
    body, n2 = re.subn(r'(android:name="stylus_blot")', r'\1\n            android:fillAlpha="0"', body)
    if n1 != 1 or n2 != 1:
        raise SystemExit("splash vector must contain exactly one stylus_stroke and one stylus_blot path")
    inner = "\n".join(("        " + line) if line else line for line in body.splitlines())
    return (
        HEADER
        + NOTE.format(what="Animated splash icon: the stylus writes the P, then the blot lands; runs once (700 ms).")
        + '<animated-vector\n'
        '    xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt">\n'
        '    <aapt:attr name="android:drawable">\n'
        f"{inner}\n"
        "    </aapt:attr>\n"
        '    <target android:name="stylus_stroke">\n'
        '        <aapt:attr name="android:animation">\n'
        "            <objectAnimator\n"
        '                android:propertyName="trimPathEnd"\n'
        '                android:valueFrom="0"\n'
        '                android:valueTo="1"\n'
        '                android:valueType="floatType"\n'
        f'                android:duration="{STROKE_MS}">\n'
        '                <aapt:attr name="android:interpolator">\n'
        "                    <pathInterpolator\n"
        '                        android:controlX1="0.2"\n'
        '                        android:controlY1="0"\n'
        '                        android:controlX2="0"\n'
        '                        android:controlY2="1" />\n'
        "                </aapt:attr>\n"
        "            </objectAnimator>\n"
        "        </aapt:attr>\n"
        "    </target>\n"
        '    <target android:name="stylus_blot">\n'
        '        <aapt:attr name="android:animation">\n'
        "            <objectAnimator\n"
        '                android:propertyName="fillAlpha"\n'
        '                android:valueFrom="0"\n'
        '                android:valueTo="1"\n'
        '                android:valueType="floatType"\n'
        f'                android:startOffset="{STROKE_MS}"\n'
        f'                android:duration="{BLOT_MS}"\n'
        '                android:interpolator="@android:interpolator/linear" />\n'
        "        </aapt:attr>\n"
        "    </target>\n"
        "</animated-vector>\n"
    )


ADAPTIVE = (
    HEADER
    + NOTE.format(what="Adaptive launcher icon (minSdk 29: no raster mipmaps).")
    + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
    '    <background android:drawable="@drawable/ic_launcher_background" />\n'
    '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
    '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
    "</adaptive-icon>\n"
)


def colors(entries: list[tuple[str, str, str]], what: str) -> str:
    lines = [HEADER, NOTE.format(what=what).replace("the SVG masters", "palette.json"), "<resources>\n"]
    for name, hexv, comment in entries:
        lines.append(f"    <!-- {comment} -->\n")
        lines.append(f'    <color name="{name}">#{hexv.lstrip("#").upper()}</color>\n')
    lines.append("</resources>\n")
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Export the brand resources into the staging tree.")
    ap.add_argument("--out", default=str(ROOT / "export" / "res"), help="res/ directory to write (default export/res)")
    args = ap.parse_args(argv)
    res = Path(args.out)
    dark = ["--palette", str(PALETTE), "--theme", "dark"]

    svg2vd("launcher-background.svg", res / "drawable/ic_launcher_background.xml")
    svg2vd("launcher-foreground.svg", res / "drawable/ic_launcher_foreground.xml")
    svg2vd("launcher-monochrome.svg", res / "drawable/ic_launcher_monochrome.xml")
    svg2vd("notification.svg", res / "drawable/ic_notification.xml")
    svg2vd("splash-mark.svg", res / "drawable/splash_mark.xml")
    svg2vd("splash-mark.svg", res / "drawable-night/splash_mark.xml", *dark)

    for qualifier in ("drawable", "drawable-night"):
        vd = (res / qualifier / "splash_mark.xml").read_text(encoding="utf-8")
        (res / qualifier / "splash_mark_animated.xml").write_text(animated(vd), encoding="utf-8")

    mip = res / "mipmap-anydpi-v26"
    mip.mkdir(parents=True, exist_ok=True)
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (mip / name).write_text(ADAPTIVE, encoding="utf-8")

    pal = json.loads(PALETTE.read_text(encoding="utf-8"))["launcher"]
    light, night = pal["splash"]["light"], pal["splash"]["dark"]
    (res / "values").mkdir(parents=True, exist_ok=True)
    (res / "values-night").mkdir(parents=True, exist_ok=True)
    (res / "values/colors.xml").write_text(colors([
        ("phono_page", light["background"], "Window and splash background (page)."),
        ("phono_ink", light["mark"], "Splash mark (ink)."),
        ("phono_launcher_tile", pal["tile"], "Launcher tile (launcher kraft); same in both themes."),
    ], "Window, splash and launcher colours."), encoding="utf-8")
    (res / "values-night/colors.xml").write_text(colors([
        ("phono_page", night["background"], "Window and splash background (soot)."),
        ("phono_ink", night["mark"], "Splash mark (bone)."),
    ], "Window and splash colours, dark theme."), encoding="utf-8")
    print(f"brand resources written to {res.name}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
