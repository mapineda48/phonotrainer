def kt_color(hex_value: str) -> str:
    v = hex_value.strip().lstrip("#")
    if not re.fullmatch(r"[0-9a-fA-F]{6}", v):
        raise ConversionError(f"not a #rrggbb colour: {hex_value!r}")
    return f"Color(0xFF{v.upper()})"


def kt_float(value: float) -> str:
    text = repr(float(value))
    return text + "f"


def kt_ident(key: str) -> str:
    parts = re.split(r"[-_ ]+", key)
    ident = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if not re.fullmatch(r"[a-z][A-Za-z0-9]*", ident):
        raise ConversionError(f"cannot name {key!r} in Kotlin")
    return ident


def kt_upper(key: str) -> str:
    ident = kt_ident(key)
    return re.sub(r"(?<!^)([A-Z])", r"_\1", ident).upper()


class KtWriter:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.depth = 0

    def line(self, text: str = "") -> None:
        self.lines.append(("  " * self.depth + text) if text else "")

    def open(self, text: str) -> None:
        self.line(text + " {")
        self.depth += 1

    def close(self) -> None:
        self.depth -= 1
        self.line("}")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def generate_palette(p: dict) -> str:
    """theme/Palette.kt: the raw values of palette.json (design 12.1) and a flat index the drift test compares."""
    index_colors: list[tuple[str, str]] = []  # (json path, Kotlin expression)
    index_numbers: list[tuple[str, str]] = []
    w = KtWriter()
    w.lines.append(GENERATED_HEADER.format(source="palette.json").rstrip("\n"))
    w.line(f"package {PACKAGE}.theme")
    w.line()
    w.line("import androidx.compose.ui.graphics.Color")
    w.line()

    def theme_object(path: str, title: str, tokens: dict, doc: str) -> None:
        w.line(f"/** {doc} */")
        w.open(f"object {title}")
        for key, value in tokens.items():
            if key.startswith("_"):
                continue
            ident = kt_ident(key)
            json_path = f"{path}.{key}"
            if isinstance(value, str):
                w.line(f"val {ident}: Color = {kt_color(value)}")
                index_colors.append((json_path, f"{qualified}.{ident}"))
            elif isinstance(value, dict) and "hex" in value:
                w.line(f"/** {key}: {value['hex']} at {value['alpha']} over {value.get('over', 'page')}. */")
                w.line(f"val {ident}: Color = {kt_color(value['hex'])}")
                w.line(f"const val {kt_upper(key)}_ALPHA: Float = {kt_float(value['alpha'])}")
                index_colors.append((json_path, f"{qualified}.{ident}"))
                index_numbers.append((json_path + ".alpha", f"{qualified}.{kt_upper(key)}_ALPHA"))
            elif isinstance(value, list):
                w.line(f"val {ident}: List<Color> = listOf({', '.join(kt_color(v) for v in value)})")
                for i, _ in enumerate(value):
                    index_colors.append((f"{json_path}[{i}]", f"{qualified}.{ident}[{i}]"))
            elif isinstance(value, (int, float)):
                w.line(f"const val {kt_upper(key)}: Float = {kt_float(value)}")
                index_numbers.append((json_path, f"{qualified}.{kt_upper(key)}"))
            else:
                raise ConversionError(f"palette.json {json_path}: unsupported value {value!r}")
        w.close()

    w.line("/** Neutral tokens of design 2.1: \"Ink on paper\" (light) and \"Scratch on soot\" (dark). */")
    w.open("object Neutrals")
    for theme in ("light", "dark"):
        qualified = f"Neutrals.{theme.title()}"
        theme_object(f"neutrals.{theme}", theme.title(), p["neutrals"][theme], p["neutrals"][theme].get("_name", theme))
    w.close()
    w.line()

    w.line("/** Brand tokens of design 2.1 and 5.4: kraft, halftones, grain, drum and poster papers. */")
    w.open("object Brand")
    for theme in ("light", "dark"):
        qualified = f"Brand.{theme.title()}"
        theme_object(f"brand.{theme}", theme.title(), p["brand"][theme], f"Brand tokens, {theme} theme.")
    w.close()
    w.line()

    w.line("/** The family hues of design 2.3 and their tints (OKLab mix of sheet and the hue). */")
    w.open("object FamilyPalette")
    w.line(f"const val TINT_SHARE_LIGHT: Float = {kt_float(p['tintShare']['light'])}")
    w.line(f"const val TINT_SHARE_DARK: Float = {kt_float(p['tintShare']['dark'])}")
    index_numbers.append(("tintShare.light", "FamilyPalette.TINT_SHARE_LIGHT"))
    index_numbers.append(("tintShare.dark", "FamilyPalette.TINT_SHARE_DARK"))
    for name in p["families"]:
        title = "Standard" if name == "standard" else "Cvd"
        w.open(f"object {title}")
        for theme in ("light", "dark"):
            w.open(f"object {theme.title()}")
            qualified = f"FamilyPalette.{title}.{theme.title()}"
            for key in p["familyOrder"]:
                w.line(f"val {kt_ident(key)}: Color = {kt_color(p['families'][name][theme][key])}")
                index_colors.append((f"families.{name}.{theme}.{key}", f"{qualified}.{kt_ident(key)}"))
            for key in p["familyOrder"]:
                w.line(f"val {kt_ident(key)}Tint: Color = {kt_color(p['tints'][name][theme][key])}")
                index_colors.append((f"tints.{name}.{theme}.{key}", f"{qualified}.{kt_ident(key)}Tint"))
            w.close()
        w.close()
    w.close()
    w.line()

    w.line("/** The articulator's tract palette (design 2.4); anatomy never uses a family hue. */")
    w.open("object Tract")
    for theme in ("light", "dark"):
        qualified = f"Tract.{theme.title()}"
        theme_object(f"tract.{theme}", theme.title(), p["tract"][theme], f"Tract tokens, {theme} theme.")
    w.close()
    w.line()

    w.line("/** The only colours illustrations, the poster fallback and brand art use (design 2.5). */")
    w.open("object IllustrationPalette")
    for theme in ("light", "dark"):
        qualified = f"IllustrationPalette.{theme.title()}"
        theme_object(f"illustration.{theme}", theme.title(), p["illustration"][theme], f"Illustration tokens, {theme}.")
    w.close()
    w.line()

    launcher = p["launcher"]
    w.line("/** Launcher icon, share-sheet backgrounds the tile is gated against, and splash colours (design 2.6). */")
    w.open("object Launcher")
    w.line(f"val tile: Color = {kt_color(launcher['tile'])}")
    w.line(f"val mark: Color = {kt_color(launcher['mark'])}")
    index_colors.append(("launcher.tile", "Launcher.tile"))
    index_colors.append(("launcher.mark", "Launcher.mark"))
    w.line("/** A share sheet the tile must stand out from, and the contrast it needs (gate G10). */")
    w.line("data class ShareSheet(val name: String, val color: Color, val minContrast: Float)")
    w.line("val shareSheets: List<ShareSheet> = listOf(")
    w.depth += 1
    for i, (name, sheet) in enumerate(launcher["shareSheets"].items()):
        w.line(f"ShareSheet(\"{name}\", {kt_color(sheet['color'])}, {kt_float(sheet['min'])}),")
        index_colors.append((f"launcher.shareSheets.{name}.color", f"Launcher.shareSheets[{i}].color"))
        index_numbers.append((f"launcher.shareSheets.{name}.min", f"Launcher.shareSheets[{i}].minContrast"))
    w.depth -= 1
    w.line(")")
    for theme in ("light", "dark"):
        splash = launcher["splash"][theme]
        w.line(f"val splashMark{theme.title()}: Color = {kt_color(splash['mark'])}")
        w.line(f"val splashBackground{theme.title()}: Color = {kt_color(splash['background'])}")
        index_colors.append((f"launcher.splash.{theme}.mark", f"Launcher.splashMark{theme.title()}"))
        index_colors.append((f"launcher.splash.{theme}.background", f"Launcher.splashBackground{theme.title()}"))
    w.close()
    w.line()

    w.line("/** Every colour and number above by its path in palette.json, for the drift test (design 12.1). */")
    w.open("internal object PaletteIndex")
    w.line("val colors: Map<String, Color> = mapOf(")
    w.depth += 1
    for path, expr in index_colors:
        w.line(f"\"{path}\" to {expr},")
    w.depth -= 1
    w.line(")")
    w.line("val numbers: Map<String, Float> = mapOf(")
    w.depth += 1
    for path, expr in index_numbers:
        w.line(f"\"{path}\" to {expr},")
    w.depth -= 1
    w.line(")")
    w.close()
    return w.text()


def icon_property(res: str) -> str:
    if not res.startswith("ic_"):
        raise ConversionError(f"icons.json: {res} does not start with ic_")
    return "".join(part[:1].upper() + part[1:] for part in res[3:].split("_"))


def generate_icons(icons: dict) -> str:
    entries = icons["icons"]
    names = [e["res"] for e in entries]
    if len(set(names)) != len(names):
        raise ConversionError("icons.json names a resource twice")
    w = KtWriter()
    w.lines.append(GENERATED_HEADER.format(source="icons.json").rstrip("\n"))
    w.line(f"package {PACKAGE}.icons")
    w.line()
    w.line("import androidx.annotation.DrawableRes")
    w.line(f"import {PACKAGE}.R")
    w.line()
    w.line("/**")
    w.line(f" * The icon set (design 6): Lucide {icons['lucideVersion']}, {len(entries)} glyphs, 24 dp, drawn in black and tinted at")
    w.line(" * runtime. An icon is never the only cue: it sits beside a word or carries a content description.")
    w.line(" */")
    w.open("object PhonoIcons")
    group = None
    for e in entries:
        if e["group"] != group:
            group = e["group"]
            w.line()
            w.line(f"// {group}")
        meaning = e["meaning"].replace("*/", "* /")
        w.line(f"/** {meaning} (Lucide \"{e['lucide']}\", stroke {e['stroke']}). */")
        w.line("@DrawableRes")
        w.line(f"val {icon_property(e['res'])}: Int = R.drawable.{e['res']}")
    w.line()
    w.line("/** Every icon by its resource name, in the order of icons.json. */")
    w.line("val all: Map<String, Int> = linkedMapOf(")
    w.depth += 1
    for e in entries:
        w.line(f"\"{e['res']}\" to {icon_property(e['res'])},")
    w.depth -= 1
    w.line(")")
    w.close()
    return w.text()


def illustration_entries() -> list[tuple[str, float, float]]:
    out = []
    for f in sorted((EXPORT / "res" / "drawable").glob("ill_*.xml")):
        root = ET.parse(f).getroot()
        vw, vh = float(root.get(A + "viewportWidth")), float(root.get(A + "viewportHeight"))
        out.append((f.stem, vw, vh))
    return out


def generate_illustrations() -> str:
    entries = illustration_entries()
    w = KtWriter()
    w.lines.append(GENERATED_HEADER.format(source="export/res/drawable/ill_*.xml").rstrip("\n"))
    w.line(f"package {PACKAGE}.illustration")
    w.line()
    w.line("import androidx.annotation.DrawableRes")
    w.line(f"import {PACKAGE}.R")
    w.line()
    w.line("/**")
    w.line(" * The illustration set (design 7.2): engraved ink, decorative (hidden from accessibility), one vector per theme")
    w.line(" * (drawable-night holds the dark twin). Draw them at the width the layout gives and the height of [aspectOf].")
    w.line(" */")
    w.open("object PhonoIllustrations")
    for name, vw, vh in entries:
        prop = "".join(part[:1].upper() + part[1:] for part in name[4:].split("_"))
        w.line(f"/** {name}: viewport {vw:g} x {vh:g}. */")
        w.line("@DrawableRes")
        w.line(f"val {prop}: Int = R.drawable.{name}")
    w.line()
    w.line("/** Every illustration by its resource name. */")
    w.line("val all: Map<String, Int> = linkedMapOf(")
    w.depth += 1
    for name, _, _ in entries:
        prop = "".join(part[:1].upper() + part[1:] for part in name[4:].split("_"))
        w.line(f"\"{name}\" to {prop},")
    w.depth -= 1
    w.line(")")
    w.line()
    w.line("private val aspects: Map<Int, Float> = mapOf(")
    w.depth += 1
    for name, vw, vh in entries:
        prop = "".join(part[:1].upper() + part[1:] for part in name[4:].split("_"))
        w.line(f"{prop} to {kt_float(round(vw / vh, 6))},")
    w.depth -= 1
    w.line(")")
    w.line()
    w.line("/** Width over height of [illustration]'s viewport; 380:214 for the full-width scenes. */")
    w.line("fun aspectOf(@DrawableRes illustration: Int): Float = aspects[illustration] ?: DEFAULT_ASPECT")
    w.line()
    w.line(f"/** The aspect of the full-width empty-state scenes (380 x 214). */")
    w.line(f"const val DEFAULT_ASPECT: Float = {kt_float(round(380 / 214, 6))}")
    w.close()
    return w.text()


