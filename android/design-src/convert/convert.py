"""Convert the design track's staging export into :core:designsystem (work-plan WP-03, design.md 12.3).

What it does, in order:
  1. gates the inputs with the design tools: tools/check_palette.py (gates G1 to G11 on palette.json) and
     tools/lint_vectors.py (lint's VectorPath and VectorRaster rules on the staged vectors);
  2. copies every staged file of design-src/export/ (173 files: fonts, licence texts, icons, illustrations and their
     dark twins, launcher layers, the adaptive-icon XMLs, the notification icon, the splash drawables, colours and the
     frozen-name aliases) byte for byte into core/designsystem/src/main/, and removes a converted file the export no
     longer has;
  3. generates the Kotlin sources the theme reads: theme/Palette.kt (every colour of palette.json),
     icons/PhonoIcons.kt (one property per icons.json entry) and illustration/PhonoIllustrations.kt (the ill_*
     drawables and their aspect);
  4. generates assets/licenses/bundled.json (architecture 20.6) from export/assets/licenses/FONTS.txt and icons.json:
     one entry per font family and one for the Lucide set, which the licence check and the licences screen read.

Nothing in the build references design-src/: the converted files are committed in the module.

Usage (from anywhere; Python 3 standard library only)
  python3 android/design-src/convert/convert.py           convert (writes into core/designsystem)
  python3 android/design-src/convert/convert.py --check   change nothing; exit 1 when a converted file differs from
                                                           what the conversion would write, or the notices section
                                                           7.3 does not list exactly the bundled components
  python3 android/design-src/convert/convert.py --notices print the rows of THIRD-PARTY-NOTICES.md 7.3
"""

