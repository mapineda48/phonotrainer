def lucide_copyright(licence_text: str) -> str:
    lines = [line.strip() for line in licence_text.splitlines() if line.strip().startswith("Copyright")]
    return "; ".join(lines)


def generate_bundled(fonts: list[FontRecord], icons: dict, licences_dir: Path) -> str:
    families: dict[str, list[FontRecord]] = {}
    for rec in fonts:
        family = FONT_FAMILIES.get(rec.file)
        if family is None:
            raise ConversionError(f"FONTS.txt lists {rec.file}, which convert.py does not know (FONT_FAMILIES)")
        families.setdefault(family, []).append(rec)
    components = []
    for family, recs in families.items():
        first = recs[0]
        for rec in recs[1:]:
            for field in ("version", "licence", "licence_file", "copyright"):
                if getattr(rec, field) != getattr(first, field):
                    raise ConversionError(f"{family}: {rec.file} and {first.file} disagree on {field}")
        components.append(
            {
                "name": family,
                "kind": "font",
                "version": first.version,
                "licence": first.licence,
                "licenceFile": first.licence_file,
                "source": first.source,
                "copyright": first.copyright,
                "files": [{"file": r.file, "upstream": r.upstream, "sha256": r.sha256} for r in recs],
            }
        )
    lucide_text = (licences_dir / "lucide-LICENSE.txt").read_text(encoding="utf-8")
    components.append(
        {
            "name": "Lucide",
            "kind": "icons",
            "version": icons["lucideVersion"],
            # ISC for the set, MIT for the glyphs derived from Feather; both texts are in the one licence file.
            "licence": "ISC AND MIT",
            "licenceFile": "lucide-LICENSE.txt",
            "source": "https://lucide.dev",
            "copyright": lucide_copyright(lucide_text),
            "count": len(icons["icons"]),
        }
    )
    doc = {
        "schema": 1,
        "about": "Third-party material bundled in the APK that is not a library: the fonts of res/font and the "
        "vendored icon set (architecture 20.6). Generated by android/design-src/convert/convert.py from "
        "FONTS.txt and icons.json; do not edit.",
        "components": components,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def notice_rows(bundled: dict) -> list[str]:
    rows = ["| Component | Version | Licence | Files | Copyright and source |", "|---|---|---|---|---|"]
    for c in bundled["components"]:
        if c["kind"] == "font":
            files = "<br>".join(f"`{f['file']}` (SHA-256 `{f['sha256']}`)" for f in c["files"])
        else:
            files = f"{c['count']} vector drawables (`res/drawable/ic_*.xml`)"
        rows.append(
            f"| {c['name']} | {c['version']} | {c['licence']} (`assets/licenses/{c['licenceFile']}`) | {files} | "
            f"{c['copyright']}; {c['source']} |"
        )
    return rows


def notices_section(text: str) -> list[str] | None:
    lines = text.splitlines()
    try:
        start = lines.index(NOTICES_HEADING)
    except ValueError:
        return None
    out = []
    for line in lines[start + 1 :]:
        if re.match(r"#{1,3} ", line):
            break
        out.append(line)
    return out


def check_notices(bundled: dict) -> list[str]:
    if not NOTICES.exists():
        return [f"{NOTICES.name} is missing"]
    section = notices_section(NOTICES.read_text(encoding="utf-8"))
    if section is None:
        return [f"{NOTICES.name} has no section '{NOTICES_HEADING}'"]
    expected = notice_rows(bundled)
    problems = []
    table = [line for line in section if line.startswith("|")]
    if table != expected:
        missing = [r for r in expected if r not in table]
        extra = [r for r in table if r not in expected]
        for r in missing:
            problems.append(f"notices 7.3 lacks the row: {r[:120]}")
        for r in extra:
            problems.append(f"notices 7.3 has a row bundled.json does not: {r[:120]}")
        if not missing and not extra:
            problems.append("notices 7.3 lists the rows in another order than bundled.json")
    return problems


