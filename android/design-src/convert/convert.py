def run_tool(name: str, *args: str) -> None:
    result = subprocess.run(
        [sys.executable, "-B", str(TOOLS / name), *args], capture_output=True, text=True, cwd=DESIGN_SRC
    )
    if result.returncode != 0:
        sys.stdout.write(result.stdout)
        sys.stderr.write(result.stderr)
        raise ConversionError(f"{name} failed (exit {result.returncode})")
    tail = [line for line in result.stdout.strip().splitlines() if line.strip()]
    print(f"{name}: {tail[-1] if tail else 'ok'}")


def planned_outputs() -> dict[Path, bytes]:
    """Every file the conversion owns in the module, with the bytes it must hold."""
    files = export_files()
    if len(files) != EXPECTED_EXPORT_FILES:
        raise ConversionError(
            f"the export holds {len(files)} files, the plan {EXPECTED_EXPORT_FILES}: update work-plan WP-03, "
            "EXPECTED_EXPORT_FILES and the inventory test together"
        )
    icons = load_json(DESIGN_SRC / "icons.json")
    staged_icons = {f.stem for f in files if f.parent == Path("res/drawable") and f.stem.startswith("ic_")}
    brand = {"ic_launcher_background", "ic_launcher_foreground", "ic_launcher_monochrome", "ic_notification"}
    listed = {e["res"] for e in icons["icons"]}
    if staged_icons - brand != listed:
        raise ConversionError(
            f"icons.json and the staged ic_* drawables differ: missing {sorted(listed - staged_icons)}, "
            f"extra {sorted(staged_icons - brand - listed)}"
        )
    out: dict[Path, bytes] = {MODULE_MAIN / f: (EXPORT / f).read_bytes() for f in files}
    fonts = parse_fonts_txt((EXPORT / "assets" / "licenses" / "FONTS.txt").read_text(encoding="utf-8"))
    for rec in fonts:
        data = (EXPORT / "res" / "font" / rec.file).read_bytes()
        if hashlib.sha256(data).hexdigest() != rec.sha256:
            raise ConversionError(f"{rec.file}: SHA-256 differs from FONTS.txt")
    staged_fonts = {f.name for f in files if f.parent == Path("res/font")}
    if staged_fonts != {r.file for r in fonts}:
        raise ConversionError("FONTS.txt and res/font/ list different files")
    bundled = generate_bundled(fonts, icons, EXPORT / "assets" / "licenses")
    out[MODULE_MAIN / "assets" / "licenses" / "bundled.json"] = bundled.encode("utf-8")
    palette = load_json(DESIGN_SRC / "palette.json")
    out[KOTLIN_ROOT / "theme" / "Palette.kt"] = generate_palette(palette).encode("utf-8")
    out[KOTLIN_ROOT / "icons" / "PhonoIcons.kt"] = generate_icons(icons).encode("utf-8")
    out[KOTLIN_ROOT / "illustration" / "PhonoIllustrations.kt"] = generate_illustrations().encode("utf-8")
    return out


def stale_files(planned: dict[Path, bytes]) -> list[Path]:
    stale = []
    for d in MANAGED_DIRS:
        root = MODULE_MAIN / d
        if root.exists():
            stale += [p for p in sorted(root.rglob("*")) if p.is_file() and p not in planned]
    return stale


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="change nothing; exit 1 on any difference")
    mode.add_argument("--notices", action="store_true", help="print the rows of THIRD-PARTY-NOTICES.md 7.3")
    args = ap.parse_args(argv)
    try:
        if args.notices:
            planned = planned_outputs()
            bundled = json.loads(planned[MODULE_MAIN / "assets" / "licenses" / "bundled.json"])
            print("\n".join(notice_rows(bundled)))
            return 0
        run_tool("check_palette.py")
        run_tool("lint_vectors.py")
        planned = planned_outputs()
        stale = stale_files(planned)
        if args.check:
            problems = []
            for path, data in planned.items():
                if not path.exists():
                    problems.append(f"missing: {path.relative_to(ANDROID)}")
                elif path.read_bytes() != data:
                    problems.append(f"differs: {path.relative_to(ANDROID)}")
            problems += [f"not in the export: {p.relative_to(ANDROID)}" for p in stale]
            bundled = json.loads(planned[MODULE_MAIN / "assets" / "licenses" / "bundled.json"])
            problems += check_notices(bundled)
            for p in problems:
                print(p, file=sys.stderr)
            print(f"{len(planned)} converted files checked: {'clean' if not problems else f'{len(problems)} problems'}")
            return 1 if problems else 0
        written = 0
        for path, data in planned.items():
            if path.exists() and path.read_bytes() == data:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            written += 1
        for p in stale:
            p.unlink()
        print(f"{len(planned)} converted files: {written} written, {len(stale)} stale removed")
        return 0
    except (ConversionError, OSError, KeyError, ValueError, ET.ParseError) as exc:
        print(f"convert: error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
