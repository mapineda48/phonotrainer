def export_files() -> list[Path]:
    """Every staged file, relative to export/ (res/... and assets/...)."""
    files = sorted(p.relative_to(EXPORT) for p in EXPORT.rglob("*") if p.is_file())
    junk = [f for f in files if f.name.startswith(".") or "__pycache__" in f.parts]
    if junk:
        raise ConversionError(f"unexpected files in the export: {', '.join(map(str, junk))}")
    return files


def load_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


@dataclass(frozen=True)
class FontRecord:
    file: str
    upstream: str
    version: str
    source: str
    copyright: str
    licence: str
    licence_file: str
    sha256: str


def parse_fonts_txt(text: str) -> list[FontRecord]:
    """The provenance manifest: a block per font file, "Key: value" lines, indented continuation lines."""
    records: list[FontRecord] = []
    current: dict[str, str] | None = None
    last_key = ""
    name = ""

    def close() -> None:
        if current is None:
            return
        try:
            licence, licence_file = re.fullmatch(r"(\S+)\s+\((\S+)\)", current["Licence"]).groups()  # type: ignore[union-attr]
            records.append(
                FontRecord(
                    file=name,
                    upstream=current["Upstream file"].split(" (")[0].strip(),
                    version=current["Version"],
                    source=current["Source"].splitlines()[0].strip(),
                    copyright=current["Copyright"],
                    licence=licence,
                    licence_file=licence_file,
                    sha256=current["SHA-256"].lower(),
                )
            )
        except (KeyError, AttributeError) as exc:
            raise ConversionError(f"FONTS.txt: the entry for {name} lacks a field or has a bad licence line: {exc}")

    for line in text.splitlines():
        if re.fullmatch(r"[a-z0-9_]+\.ttf", line.strip()) and not line.startswith(" "):
            close()
            name, current, last_key = line.strip(), {}, ""
            continue
        if current is None or not line.strip():
            continue
        m = re.fullmatch(r"\s+([A-Za-z][A-Za-z0-9 -]*?):\s+(.*)", line)
        if m:
            last_key = m.group(1)
            current[last_key] = m.group(2).strip()
        elif last_key:
            current[last_key] += "\n" + line.strip()
    close()
    return records


