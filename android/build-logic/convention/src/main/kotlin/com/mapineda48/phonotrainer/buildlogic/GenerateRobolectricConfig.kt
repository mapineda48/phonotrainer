package com.mapineda48.phonotrainer.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes the `robolectric.properties` that every Android module's unit tests find at the root of their classpath, so
 * Robolectric runs on [sdk] without a `@Config` on each class (architecture 21.2). A test that needs another level
 * still says so with `@Config(sdk = …)`.
 */
@CacheableTask
abstract class GenerateRobolectricConfig : DefaultTask() {
  @get:Input
  abstract val sdk: Property<Int>

  @get:OutputDirectory
  abstract val outputDirectory: DirectoryProperty

  @TaskAction
  fun generate() {
    val file = outputDirectory.file("robolectric.properties").get().asFile
    file.parentFile.mkdirs()
    file.writeText("# Generated by build-logic (GenerateRobolectricConfig); architecture 21.2.\nsdk=${sdk.get()}\n")
  }
}
